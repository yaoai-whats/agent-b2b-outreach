#!/usr/bin/env python3
"""Letter builder: fill the templates with per-company variant rotation.

Design notes:
- Variants (subject, intro, closing, value point) rotate by a hash of the
  company domain (fallback: company name). The same company always
  receives the same variant; different companies do not receive
  byte-identical letters.
- Sender identity, product, and value points come from config (see
  `scripts/_config.py`); command-line arguments override them. Nothing
  business-specific is hard-coded here.
- The observation sentence is NEVER generated by this script. It must
  already be on the lead row as lead["observation"]: one clause the
  researching agent wrote from that company's real public information
  (their published range, programme, or channel activity). A row without
  an observation is not ready to write to: the script stops and says so.
  There is deliberately no generic filler fallback.
- An optional channel-partner body variant serves platforms, buying
  groups, and distributor networks (set lead["is_channel_partner"] =
  True). Its extra sentence is industry-neutral on purpose.

CLI (all sender/product arguments are optional and default to config):
    python3 letter_builder.py --lead data/leads.example.jsonl --line 1
    python3 letter_builder.py --lead data/leads.example.jsonl --line 1 \
        --sender-name "Your Name" --sender-company "Your Company" \
        --product "your product" --value "One buyer-side value sentence."
"""
import argparse
import json
import re
import sys

import _config

SUBJECTS = [
    "Wholesale enquiry: {product}",
    "{product}: a low-risk line for your range",
    "Catalogue and wholesale terms: {product}",
]

INTROS = [
    "We manufacture {product} for wholesale and contract buyers.",
    "Our factory produces {product}, supplied to importers and distributors.",
    "We are a maker of {product} selling through wholesale channels.",
]

CLOSINGS = [
    "Could I send you our catalogue and wholesale terms?",
    "Shall I send over the catalogue with the wholesale price list?",
    "Would it help if I sent the catalogue and terms?",
]

BODY = """Hi {name},

I noticed {company} {observation}.

{intro} {benefit}

{closing}

Best regards,
{sender_name}
{sender_company}
"""

PARTNER_SUBJECT = "Wholesale range proposal: {product}"

PARTNER_BODY = """Hi {name},

I noticed {company} {observation}.

{intro} {benefit} For a partner range, the practical points are consistent supply across the year, one line that works across several of your sellers' channels, and packaging ready for mixed-channel distribution.

{closing}

Best regards,
{sender_name}
{sender_company}
"""


def extract_name(contact):
    """Clean a raw contact field down to a greeting name.

    Rules: empty or unverified marker returns "there"; bracketed or
    parenthesised notes and honorifics are stripped; "A and B" style pairs
    keep both first names joined with "and"; a field with no usable name
    returns "there" rather than guessing.
    """
    if not contact or contact.strip() in ("", "-"):
        return "there"
    if "unverified" in contact.lower():
        return "there"
    first = contact.split("/")[0]
    first = re.split(r"[(\[,]", first)[0]
    first = re.sub(r"^(Mr|Mrs|Ms|Dr)\.?\s+", "", first.strip(), flags=re.I)
    tokens = re.findall(r"[A-Za-z\u00C0-\u00D6\u00D8-\u00F6\u00F8-\u00FF'\-]+", first)
    if not tokens:
        return "there"
    if re.search(r"\band\b", first) and len(tokens) >= 2:
        return tokens[0] + " and " + tokens[1]
    return tokens[0]


def _variant_idx(lead, salt):
    """Stable per-company variant index from the domain (or company name)."""
    key = (lead.get("domain") or lead.get("company") or "").lower()
    h = 0
    for ch in key + "|" + str(salt):
        h = (h * 31 + ord(ch)) & 0xFFFFFFFF
    return h


def build_email(lead, sender_name, sender_company, product, value_point,
                observation=None):
    """Return (to, subject, body) for one lead row.

    Raises ValueError when the row has no observation: research comes
    first, and this script will not invent a filler sentence.
    """
    name = extract_name(lead.get("contact", ""))
    company = lead["company"]
    obs = observation or (lead.get("observation") or "").strip()
    if not obs:
        raise ValueError(
            f"lead '{company}' has no 'observation' field: research the "
            "company's public information first and store one factual "
            "clause on the row; this script does not generate filler "
            "observations")
    intro = INTROS[_variant_idx(lead, 2) % len(INTROS)].format(product=product)
    closing = CLOSINGS[_variant_idx(lead, 4) % len(CLOSINGS)]
    emails = lead.get("emails") or []
    to = lead.get("useful_email") or (emails[0] if emails else "")
    if lead.get("is_channel_partner"):
        subject = PARTNER_SUBJECT.format(product=product)
        body = PARTNER_BODY.format(
            name=name, company=company, observation=obs, intro=intro,
            benefit=value_point, closing=closing,
            sender_name=sender_name, sender_company=sender_company)
    else:
        subject = SUBJECTS[_variant_idx(lead, 1) % len(SUBJECTS)].format(
            product=product)
        body = BODY.format(
            name=name, company=company, observation=obs, intro=intro,
            benefit=value_point, closing=closing,
            sender_name=sender_name, sender_company=sender_company)
    return to, subject, body


def resolve_defaults(args):
    """CLI arguments win; config supplies whatever the CLI left unset.

    Returns (sender_name, sender_company, product, value_point, missing).
    value_point stays None when neither the CLI nor a per-company choice
    has picked one yet; the caller then rotates config value_points by
    the company hash.
    """
    sender_name = args.sender_name or _config.get("sender_name", "")
    sender_company = args.sender_company or _config.get("sender_company", "")
    product = args.product or _config.get("product", "")
    value_point = args.value or None
    missing = [label for label, val in
               (("sender_name", sender_name), ("sender_company", sender_company),
                ("product", product)) if not val]
    return sender_name, sender_company, product, value_point, missing


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description="Build one letter from a lead row.")
    parser.add_argument("--lead", required=True, help="Path to a leads .jsonl file.")
    parser.add_argument("--line", type=int, default=1,
                        help="1-based line number of the lead to build for.")
    parser.add_argument("--sender-name", default=None,
                        help="Defaults to sender_name in config.")
    parser.add_argument("--sender-company", default=None,
                        help="Defaults to sender_company in config.")
    parser.add_argument("--product", default=None,
                        help="Defaults to product in config.")
    parser.add_argument("--value", default=None,
                        help="One buyer-side value sentence. Defaults to a "
                             "value_points entry from config, rotated per company.")
    parser.add_argument("--observation", default=None,
                        help="Override the observation clause stored on the lead row.")
    args = parser.parse_args()
    with open(args.lead, encoding="utf-8") as fh:
        rows = [json.loads(line) for line in fh if line.strip()]
    lead_row = rows[args.line - 1]
    sender_name, sender_company, product, value_point, missing = \
        resolve_defaults(args)
    if missing:
        print("ERROR: missing sender/product values; set them in config or "
              f"pass them on the command line: {', '.join(missing)}",
              file=sys.stderr)
        sys.exit(2)
    if value_point is None:
        points = _config.get("value_points", [])
        if points:
            value_point = points[_variant_idx(lead_row, 3) % len(points)]
    if not value_point:
        print("ERROR: no value point: set value_points in config or pass "
              "--value.", file=sys.stderr)
        sys.exit(2)
    try:
        to_addr, subj, letter_body = build_email(
            lead_row, sender_name, sender_company, product,
            value_point, args.observation)
    except ValueError as exc:
        print(f"ERROR: {exc}", file=sys.stderr)
        sys.exit(2)
    print(f"To: {to_addr}")
    print(f"Subject: {subj}")
    print()
    print(letter_body)
