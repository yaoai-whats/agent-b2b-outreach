#!/usr/bin/env python3
"""Letter builder: six skeletons plus phrase-level spintax variants.

Design notes:
- One skeleton plus synonym rotation is not enough: hundreds of letters
  built that way share one structural fingerprint. This builder uses six
  genuinely different skeletons (paragraph order, length band, and call to
  action all differ), narrows the pool by buyer type, then picks one
  skeleton per company by a hash of the company domain (fallback:
  company name). The same company always receives the same skeleton;
  different companies are spread across skeletons.
- Inside each skeleton, phrase-level spintax blocks {A|B|C} vary the
  wording block by block, again by company-domain hash, so the preview,
  the quality gate, and the sent letter all see the same text. Names,
  company names, and numbers never go inside a spintax block.
- Sender identity, product, and value points come from config (see
  `scripts/_config.py`); command-line arguments override them. Nothing
  business-specific is hard-coded here. The skeleton texts use only the
  {product} and {product_value} slots for product content.
- The observation sentence is NEVER generated by this script. It must
  already be on the lead row as lead["observation"]: one clause the
  researching agent wrote from that company's real public information
  (their published range, programme, or channel activity). A row without
  an observation is not ready to write to: the script stops and says so.
  There is deliberately no generic filler fallback.
- An optional channel-partner skeleton set serves platforms, buying
  groups, and distributor networks (set lead["is_channel_partner"] =
  True). Its extra sentence is industry-neutral on purpose: consistent
  supply across the year, one line across several downstream channels,
  packaging ready for mixed-channel distribution.

CLI (all sender/product arguments are optional and default to config):
    python3 letter_builder.py --lead data/leads.example.jsonl --line 1
    python3 letter_builder.py --lead data/leads.example.jsonl --line 1 \
        --sender-name "Your Name" --sender-company "Your Company" \
        --product "your product" --value "One buyer-side value sentence."
"""
import argparse
