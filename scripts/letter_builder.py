def extract_name(contact):
    """Clean a raw contact field down to a greeting name.

    Rules: empty or unverified marker returns "there"; bracketed or
    parenthesised notes and honorifics are stripped; "A and B" style pairs
    keep both first names joined with "and"; a field with no usable name
    returns "there" rather than guessing.
    """
    if not contact or contact.strip() in ("", "-"):
        return "there"
    if "unverified" in contact.lower():
        return "there"
    first = contact.split("/")[0]
    first = re.split(r"[(\[,]", first)[0]
    first = re.sub(r"^(Mr|Mrs|Ms|Dr)\.?\s+", "", first.strip(), flags=re.I)
    tokens = re.findall(r"[A-Za-z\u00C0-\u00D6\u00D8-\u00F6\u00F8-\u00FF'\-]+", first)
    if not tokens:
        return "there"
    if re.search(r"\band\b", first) and len(tokens) >= 2:
        return tokens[0] + " and " + tokens[1]
    return tokens[0]


def _variant_idx(lead, salt):
    """Stable per-company variant index from the domain (or company name)."""
    key = (lead.get("domain") or lead.get("company") or "").lower()
    h = 0
    for ch in key + "|" + str(salt):
        h = (h * 31 + ord(ch)) & 0xFFFFFFFF
    return h


def _split_spin_options(inner):
    """Split a spintax block on top-level | (nested braces do not split)."""
    parts, depth, cur = [], 0, []
    for ch in inner:
        if ch == "{":
            depth += 1
        elif ch == "}":
            depth -= 1
        if ch == "|" and depth == 0:
            parts.append("".join(cur))
            cur = []
        else:
            cur.append(ch)
    parts.append("".join(cur))
    return [p.strip() for p in parts if p.strip()]


def _spin(text, lead, salt):
    """Render spintax blocks {A|B|C}: block n takes its option by
    _variant_idx(lead, salt + n). Plain {placeholder} braces without a
    pipe are left untouched for the later .format() step."""
    out = []
    i, block_no = 0, 0
    n = len(text)
    while i < n:
        if text[i] == "{":
            depth, j, has_pipe = 0, i, False
            while j < n:
                c = text[j]
                if c == "{":
                    depth += 1
                elif c == "}":
                    depth -= 1
                    if depth == 0:
                        break
                elif c == "|" and depth == 1:
                    has_pipe = True
                j += 1
            if j < n and has_pipe:
                options = _split_spin_options(text[i + 1:j])
                if options:
                    out.append(options[_variant_idx(lead, salt + block_no)
                                       % len(options)])
                    block_no += 1
                    i = j + 1
                    continue
        out.append(text[i])
        i += 1
    return "".join(out)


def _company_short(company):
    """Short company name for subject lines: drop parenthetical notes and
    legal suffixes, keep at most the first four words."""
    s = company or ""
    s = re.sub(r"\([^)]*\)", "", s)
    s = re.sub(r"\b(Inc|LLC|Corp|Co|Ltd|Limited|GmbH|BV|NV|SA|SAS|SRL|SL|Oy|"
               r"Pty|PLC|Group|Holdings|International)\b\.?", "", s,
               flags=re.I)
    words = s.split()
    return " ".join(words[:4]).strip() or (company or "")


def _first_sentence(obs):
    """First sentence of the observation clause, verbatim (short skeleton)."""
    m = re.split(r"(?<=[.!?])\s+", obs, maxsplit=1)
    return m[0].strip()


# ---------------------------------------------------------------------------
# Skeleton pool: narrow by buyer type, then pick by domain hash (salt 21).
# 1 standard intro / 2 question opening / 3 three-line short /
# 4 buyer ledger / 5 seasonal scenario / 6 direct supply
# ---------------------------------------------------------------------------
def _skeleton_pool(lead):
    t = " ".join(str(lead.get(k) or "") for k in
                 ("buyer_category", "customer_type", "buyer_type")).lower()
    if any(k in t for k in ("wholesale", "import", "distributor", "supply")):
        return [1, 2, 4, 6]
    if "gift" in t:
        return [1, 2, 3, 5]
    if any(k in t for k in ("retail", "chain", "store", "ecommerce",
                            "e-commerce", "department")):
        return [1, 2, 3, 6]
    return [1, 2, 4, 6]


def pick_skeleton(lead, pool=None):
    pool = pool or _skeleton_pool(lead)
    return pool[_variant_idx(lead, 21) % len(pool)]


